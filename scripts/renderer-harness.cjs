async function until(fn) {
  const end = Date.now() + 4000;
  while (Date.now() < end) {
    if (await evaluate(fn)) return;
    await new Promise(resolve => setTimeout(resolve, 15));
  }
  throw new Error("Renderer condition timed out: " + fn.toString());
}
